// Get the icon that corresponds to a feature type
export function getFeatureIcon(type: string): string {
  switch (type) {
    case 'Point':
      return POINT_ICON;
    case 'LineString':
      return LINE_ICON;
    case 'Polygon':
      return POLYGON_ICON;
    case 'Image':
      return IMAGE_ICON;
    default:
      return POINT_ICON;
  }
}
